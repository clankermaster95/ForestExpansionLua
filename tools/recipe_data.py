"""Generate authoritative Lua recipe/pricing data from editable object records."""
from pathlib import Path
import json
import data_store as ds
from item_costs import Catalog
ROOT=Path(__file__).resolve().parents[1]

def render():
    catalog=Catalog()
    spec=catalog.spec; rows=catalog.rows
    objects={(x['kind'],x['rawcode']):x for x in rows}
    recipes=spec['recipes']; results={x['result'] for x in recipes}
    assert len(results)==len(recipes),'duplicate result'
    scrolls=[x['scroll'] for x in recipes if x.get('scroll')]
    assert len(scrolls)==len(set(scrolls)),'duplicate scroll'
    by_result={x['result']:x for x in recipes}
    def visit(raw,stack):
        if raw not in by_result:return
        assert raw not in stack,'cyclic recipe'
        for part in by_result[raw]['components']:visit(part,stack+[raw])
    for raw in results:visit(raw,[])
    catalog.validate_ancient_shops()
    stock={raw:catalog.shop_items(raw) for raw in spec['shops']}
    ids=sorted(results|set(scrolls)|{x for r in recipes for x in r['components']}|set(spec.get('additional_prices',[]))|{x for items in stock.values() for x in items})
    lines=['-- Generated by tools/recipe_data.py from data/gameplay and object records.',
           '-- Do not edit prices here. The regular build regenerates this module.',
           'FE_RecipeData = {items = {}, recipes = {}, shops = {}, stock = {}}']
    for raw in ids:
        gold,lumber=catalog.price(raw)
        assert isinstance(gold,int) and isinstance(lumber,int) and gold>=0 and lumber>=0
        lines.append(f'FE_RecipeData.items[FourCC("{raw}")] = {{gold={gold}, lumber={lumber}, name={json.dumps(catalog.name(raw),ensure_ascii=False)}}}')
    for recipe in recipes:
        scroll=f'FourCC("{recipe["scroll"]}")' if recipe.get('scroll') else 'nil'
        parts=', '.join(f'FourCC("{x}")' for x in recipe['components'])
        lines.append(f'FE_RecipeData.recipes[#FE_RecipeData.recipes + 1] = {{scroll={scroll}, result=FourCC("{recipe["result"]}"), components={{{parts}}}}}')
    for raw in spec['shops']:
        lines.append(f'FE_RecipeData.shops[FourCC("{raw}")] = true')
        lines.append(f'FE_RecipeData.stock[FourCC("{raw}")] = {{'+', '.join(f'[FourCC("{item}")]=true' for item in stock[raw])+'}')
    return '\n'.join(lines)+'\n'

def generate():
    code=render(); path=ROOT/'src/items/recipe_data.lua'
    if not path.exists() or path.read_text(encoding='utf-8')!=code:path.write_text(code,encoding='utf-8',newline='\n')

if __name__=='__main__':generate()
