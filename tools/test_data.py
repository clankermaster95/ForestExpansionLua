"""Generate a deterministic spawn/search catalog from the map's object data."""
from pathlib import Path
import json,re
from item_costs import Catalog
import faction_data
ROOT=Path(__file__).resolve().parents[1]

def render():
    cfg=json.loads((ROOT/'project.json').read_text())
    c=Catalog(); lines=['-- Generated by tools/test_data.py; edit object data/project.json, not this file.',
                       'FE_TestData = {units={}, items={}, catalog={}, pickers={}, releaseLabel='+
                       json.dumps(cfg['version']+' '+cfg['revision'])+'}']
    for kind in ('units','items'):
        rows={r['rawcode']:r for r in c.rows if r['kind'] in (kind,kind+'_skin')}
        for raw,row in sorted(rows.items()):
            name=str(c.fields(kind,raw).get('unam',row['name']))
            name=re.sub(r'\|c[0-9a-fA-F]{8}|\|r','',name).replace('|n',' ')
            lines.append('FE_TestData.'+kind+'['+json.dumps(raw)+'] = true')
            lines.append('FE_TestData.catalog[#FE_TestData.catalog+1] = {kind='+json.dumps(kind)+
                         ', raw='+json.dumps(raw)+', name='+json.dumps(name,ensure_ascii=False)+'}')
    factions=faction_data.load()
    for kind in ('expanders','ancients'):
        for entry in factions[kind]:
            ban,raw,shop=entry['ban'],entry['raw'],entry['shop']
            solo=', soloOnly=true' if entry.get('soloOnly') else ''
            lines.append('FE_TestData.pickers[#FE_TestData.pickers+1] = {raw='+json.dumps(raw)+', shop='+json.dumps(shop)+', ban='+json.dumps(ban)+solo+'}')
    return '\n'.join(lines)+'\n'

def generate():
    path=ROOT/'src/commands/test_data.lua'; code=render()
    if not path.exists() or path.read_text(encoding='utf-8')!=code:
        path.write_text(code,encoding='utf-8',newline='\n')

if __name__=='__main__':generate()
