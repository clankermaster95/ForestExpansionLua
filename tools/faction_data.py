"""Authoritative ordered faction data for picking, bans and solo-test discovery."""
from pathlib import Path
import json
import re

ROOT = Path(__file__).resolve().parents[1]
BEGIN = '-- BEGIN GENERATED FACTION CATALOG'
END = '-- END GENERATED FACTION CATALOG'


def load():
    data = json.loads((ROOT/'data/gameplay/factions.json').read_text(encoding='utf-8'))
    validate(data)
    return data


def validate(data):
    entries = data['expanders'] + data['ancients']
    assert len(data['expanders']) == 20 and len(data['ancients']) == 11
    for field in ('key', 'raw', 'ban'):
        assert len({row[field] for row in entries}) == len(entries), field
    assert len(data['banOrder']) == len(entries)
    assert set(data['banOrder']) == {row['key'] for row in entries}
    expander_keys = {row['key'] for row in data['expanders']}
    ancient_keys = {row['key'] for row in data['ancients']}
    for field,count,keys in (('randomExpanders',18,expander_keys),
                            ('randomAncients',33,ancient_keys),
                            ('spellbringerOrder',11,ancient_keys)):
        assert len(data[field])==count and set(data[field]) <= keys,field
    assert set(data['spellbringerOrder']) == ancient_keys, 'Spellbringer must cover every Ancient once'
    for row in data['ancients']:
        assert re.fullmatch(r'[A-Za-z0-9]{4}', row.get('spellbringerAbility', '')), row['key']
    aliases = []
    for row in entries:
        assert re.fullmatch(r'[A-Za-z0-9]{4}', row['raw'])
        assert re.fullmatch(r'gg_unit_[A-Za-z0-9]{4}_\d+', row['shop'])
        assert row['ban'] == 'udg_Banned' + row['key']
        assert row['stock'] in (0, 1) and row['maximum'] == 1
        assert type(row['closeAtCutoff']) is bool
        assert row['aliases'] and all(alias.startswith('-ban ') for alias in row['aliases'])
        aliases.extend(row['aliases'])
    assert len(set(aliases)) == len(aliases), 'Duplicate exact-match ban alias'


def render():
    data = load()
    quote = lambda value: json.dumps(value, ensure_ascii=False)
    rows = [BEGIN, '-- Generated by tools/faction_data.py from data/gameplay/factions.json.',
            '-- Names resolve at use time, after placed handles and mutable ban flags exist.',
            'FE_Factions = { byKey = {} }']
    for kind in ('expanders', 'ancients'):
        rows.append('FE_Factions.' + kind + ' = {')
        for entry in data[kind]:
            fields = [key+'='+quote(entry[key]) for key in ('key', 'raw', 'shop', 'ban', 'message')]
            fields += ['stock='+str(entry['stock']), 'maximum='+str(entry['maximum']),
                       'closeAtCutoff='+str(entry['closeAtCutoff']).lower(),
                       'aliases={'+', '.join(map(quote, entry['aliases']))+'}']
            if 'spellbringerAbility' in entry:
                assert re.fullmatch(r'[A-Za-z0-9]{4}',entry['spellbringerAbility'])
                fields.append('spellbringerAbility='+quote(entry['spellbringerAbility']))
            rows.append('    { '+', '.join(fields)+' },')
        rows.append('}')
    rows.append('FE_Factions.banOrder = {'+', '.join(map(quote, data['banOrder']))+'}')
    for field in ('randomExpanders','randomAncients','spellbringerOrder'):
        rows.append('FE_Factions.'+field+' = {'+', '.join(map(quote,data[field]))+'}')
    rows.extend(['for _, kind in ipairs({"expanders", "ancients"}) do',
                 '    for _, entry in ipairs(FE_Factions[kind]) do FE_Factions.byKey[entry.key] = entry end',
                 'end', END])
    return '\n'.join(rows)


def generate():
    path = ROOT/'src/game/selection.lua'
    source = path.read_text(encoding='utf-8')
    block = render()
    if BEGIN in source:
        source, count = re.subn(re.escape(BEGIN)+r'.*?'+re.escape(END), lambda _: block, source, flags=re.S)
        assert count == 1
    else:
        source = block + '\n\n' + source
    if source != path.read_text(encoding='utf-8'):
        path.write_text(source, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    generate()
